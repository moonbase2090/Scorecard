fn file_group(out: &mut String, file: &FileGroup, anchors: &mut Vec<String>) {
    let errors = file.count("error");
    let open = errors > 0 && file.total() <= OPEN_LIMIT;
    out.push_str(&format!(
        "<details class=\"fg\"{}><summary><span class=\"fg-name\">",
        if open { " open" } else { "" }
    ));
    out.push_str(&path_html(&file.path, None));
    out.push_str("</span><span class=\"pills\">");
    for sev in ["error", "warning", "info"] {
        let n = file.count(sev);
        if n > 0 {
            out.push_str(&format!(
                "<span class=\"pill p-{sev}\">{}</span>",
                plural(n, sev, &format!("{sev}s"))
            ));
        }
    }
    out.push_str("</span></summary><div class=\"gbody\">");
    for group in &file.rules {
        out.push_str(&format!(
            "<div class=\"rg\"><h3 class=\"rh\"><code>{}</code><span>{}</span></h3>",
            esc(group.rule),
            group.total()
        ));
        for row in group.rows.iter().take(GROUP_LIMIT) {
            finding_row(out, row, &file.path, anchors);
        }
        if group.rows.len() > GROUP_LIMIT {
            out.push_str(&format!(
                "<p class=\"note\">{} more <code>{}</code> rows in this file are in the JSON and SARIF reports.</p>",
                group.rows.len() - GROUP_LIMIT,
                esc(group.rule)
            ));
        }
        out.push_str("</div>");
    }
    out.push_str("</div></details>\n");
}

/// Stable, unique anchor per finding id: `f-` plus an FNV-1a hash.
fn anchor(id: &str, taken: &mut Vec<String>) -> String {
    let hash = id.bytes().fold(0xcbf2_9ce4_8422_2325u64, |h, b| {
        (h ^ u64::from(b)).wrapping_mul(0x100_0000_01b3)
    });
    let base = format!("f-{hash:016x}");
    let mut name = base.clone();
    let mut n = 1;
    while taken.contains(&name) {
        n += 1;
        name = format!("{base}-{n}");
    }
    taken.push(name.clone());
    name
}

fn finding_row(out: &mut String, row: &Row, path: &str, anchors: &mut Vec<String>) {
    let f = row.finding;
    let sev = severity(f);
    let id = anchor(&f.id, anchors);
    let line = row.lines.first().copied();
    let location = match line {
        Some(line) => format!("{path}:{line}"),
        None => path.to_string(),
    };
    let search = format!(
        "{location} {} {} {} {}",
        f.rule,
        f.engine,
        f.symbol.as_deref().unwrap_or(""),
        f.message
    )
    .to_lowercase();
    out.push_str(&format!(
        "<article class=\"f s-{sev}\" id=\"{id}\" data-sev=\"{sev}\" data-eng=\"{}\" data-rule=\"{}\" data-n=\"{}\" data-q=\"{}\"><div class=\"f-main\"><span class=\"sev s-{sev}\">{sev}</span><p class=\"msg\">{}</p>",
        esc(&f.engine),
        esc(&f.rule),
        row.count,
        esc(&search),
        esc(&f.message)
    ));
    if row.count > 1 {
        out.push_str(&format!("<span class=\"rep\">×{}</span>", row.count));
    }
    out.push_str("</div><div class=\"f-meta\">");
    if path != REPO_LEVEL {
        out.push_str(&path_html(path, line));
    }
    if row.lines.len() > 1 {
        let more: Vec<String> = row.lines[1..].iter().take(12).map(u32::to_string).collect();
        out.push_str(&format!(
            "<span class=\"lines\">also line {}</span>",
            more.join(", ")
        ));
    }
    if let Some(symbol) = &f.symbol {
        out.push_str(&format!("<code>{}</code>", esc(symbol)));
    }
    out.push_str(&format!("<span>{}</span></div>", esc(&f.engine)));
    finding_extras(out, row);
    out.push_str(&format!(
        "<div class=\"f-act js-only\"><button type=\"button\" data-copy=\"{}\">Copy</button><a href=\"#{id}\">Link</a></div></article>",
        esc(&format!("{location} {} {}", f.rule, f.message))
    ));
}

fn finding_extras(out: &mut String, row: &Row) {
    let f = row.finding;
    let (functions, more) = evidence_functions(f);
    if !functions.is_empty() {
        out.push_str("<ul class=\"fnlist\">");
        for (location, symbol) in &functions {
            out.push_str(&format!(
                "<li>{} <code>{}</code></li>",
                path_html(location, None),
                esc(symbol)
            ));
        }
        if more > 0 {
            out.push_str(&format!("<li>{more} more</li>"));
        }
        out.push_str("</ul>");
    }
    if row.untested {
        out.push_str("<p class=\"note\">Also <code>complexity.untested</code>: no coverage at this complexity.</p>");
    }
    if let Some(action) = &f.suggested_action {
        out.push_str(&format!("<p class=\"fix\"><b>Fix:</b> {}</p>", esc(action)));
    }
    if let Some(log) = raw_log(f) {
        out.push_str(&format!(
            "<details class=\"log\"><summary>Full output</summary><pre>{}</pre></details>",
            esc(log)
        ));
    }
}
/// Functions shown per finding from `evidence.functions`.
const FUNCTION_LIMIT: usize = 20;

/// The functions a finding lists in `evidence.functions` (for example the
/// functions `coverage.unmatched` found no coverage record for), as
/// ("file:line", symbol) pairs, plus how many more exist beyond what is
/// shown. The engine caps the list, so `evidence.unmatched` can give the
/// real total. Empty when the finding already names its one function.
pub(crate) fn evidence_functions(finding: &sc_core::Finding) -> (Vec<(String, String)>, usize) {
    let Some(items) = finding
        .evidence
        .get("functions")
        .and_then(|functions| functions.as_array())
    else {
        return (Vec::new(), 0);
    };
    let listed: Vec<(String, String)> = items
        .iter()
        .filter_map(|item| {
            let file = item.get("file")?.as_str()?;
            let symbol = item.get("symbol")?.as_str()?;
            let line = item
                .get("line")
                .or_else(|| item.get("span").and_then(|span| span.get("start_line")))
                .and_then(|line| line.as_u64());
            let location = match line {
                Some(line) => format!("{file}:{line}"),
                None => file.to_string(),
            };
            Some((location, symbol.to_string()))
        })
        .collect();
    if listed.len() == 1 && finding.symbol.as_deref() == Some(listed[0].1.as_str()) {
        return (Vec::new(), 0);
    }
    let total = finding
        .evidence
        .get("unmatched")
        .and_then(|count| count.as_u64())
        .map(|count| count as usize)
        .unwrap_or(listed.len())
        .max(listed.len());
    let shown: Vec<_> = listed.into_iter().take(FUNCTION_LIMIT).collect();
    let more = total - shown.len();
    (shown, more)
}

/// The raw command output a finding carries in `evidence.log` (lint and
/// test failures). The message is the first useful line; the log sits
/// behind a disclosure so the compile preamble never leads the card.
pub(crate) fn raw_log(finding: &sc_core::Finding) -> Option<&str> {
    finding
        .evidence
        .get("log")
        .and_then(|log| log.as_str())
        .map(str::trim_end)
        .filter(|log| !log.trim().is_empty())
}

fn plural(n: usize, one: &str, many: &str) -> String {
    format!("{n} {}", if n == 1 { one } else { many })
}

fn crap(out: &mut String, card: &Scorecard) {
    out.push_str(&format!(
        "<section id=\"crap\" aria-labelledby=\"crap-h\"><h2 id=\"crap-h\">worst crap · threshold {}</h2><div class=\"card\">",
        card.crap.threshold
    ));
    if !ran(card, &["crap"]) {
        out.push_str("<p class=\"note\">Not measured: the crap engine did not run. See Engines below for why.</p></div></section>\n");
        return;
    }
    if let Some(line) = diff_baseline(card) {
        out.push_str(&format!("<p class=\"note\">{}</p>", esc(&line)));
    }
    let measured = coverage_measured(card);
    if !measured {
        out.push_str(&format!("<p class=\"note\">{COVERAGE_NOT_MEASURED}</p>"));
    }
    if card.crap.worst.is_empty() {
        out.push_str(
            "<p class=\"note\">No functions in the reporting window.</p></div></section>\n",
        );
        return;
    }
    out.push_str("<table class=\"stack\"><colgroup><col class=\"c-num\"><col class=\"c-num\"><col class=\"c-cov\"><col><col></colgroup><thead><tr><th scope=\"col\">CRAP</th><th scope=\"col\">CC</th><th scope=\"col\">coverage</th><th scope=\"col\">symbol</th><th scope=\"col\">file</th></tr></thead><tbody>");
    let repo = card.repo.as_str();
    for row in &card.crap.worst {
        let over = row.crap > f64::from(card.crap.threshold);
        let cov = (row.coverage.clamp(0.0, 1.0) * 100.0).round() as i64;
        let coverage = if measured {
            format!(
                "<div class=\"cov\"><span class=\"bar\" aria-hidden=\"true\"><i class=\"{}\" style=\"width:{cov}%\"></i></span><small>{cov}%</small></div>",
                level(row.coverage)
            )
        } else {
            "<span class=\"nm\">not measured</span>".to_string()
        };
        out.push_str(&format!(
            "<tr><td data-label=\"CRAP\"><span class=\"pill p-{}\">{}</span></td><td data-label=\"CC\">{}</td><td data-label=\"coverage\">{coverage}</td><td data-label=\"symbol\"><code>{}</code></td><td data-label=\"file\">{}</td></tr>",
            if over { "error" } else { "info" },
            esc(&fmt_num(row.crap)),
            row.cc,
            esc(&row.symbol),
            path_html(&rel_path(&row.file, repo), None)
        ));
    }
    out.push_str("</tbody></table></div></section>\n");
}

/// Why an engine did not run, and the command or setting that runs it.
fn skip_reason(card: &Scorecard, engine: &str) -> (String, Option<String>) {
    if let Some(f) = card
        .findings
        .iter()
        .find(|f| f.engine == engine && f.rule == "engine.unavailable")
    {
        return (f.message.clone(), f.suggested_action.clone());
    }
    match engine {
        "spec" => (
            "No spec file was given.".into(),
            Some("sc analyze . --spec TASK.md".into()),
        ),
        "mutation" => (
            "Mutation testing is off by default.".into(),
            Some("sc analyze . --mutation diff".into()),
        ),
        "llm" => (
            "The model review is off by default.".into(),
            Some("sc analyze . --llm on --spec TASK.md".into()),
        ),
        _ => (format!("The {} pack does not run it.", card.pack), None),
    }
}

fn run_details(out: &mut String, card: &Scorecard) {
    out.push_str("<section id=\"run\" aria-labelledby=\"run-h\"><h2 id=\"run-h\">Run details</h2><div class=\"cards\"><div class=\"card\"><h3>Engines</h3><ul class=\"chips\">");
    for engine in &card.engines_run {
        out.push_str(&format!("<li>{}</li>", esc(engine)));
    }
    out.push_str("</ul>");
    if !card.engines_skipped.is_empty() {
        out.push_str("<h4>Skipped</h4><ul class=\"skips\">");
        for engine in &card.engines_skipped {
            let (why, fix) = skip_reason(card, engine);
            out.push_str(&format!("<li><code>{}</code> {}", esc(engine), esc(&why)));
            if let Some(fix) = fix {
                out.push_str(&format!(
                    "<span class=\"fixcmd\">To run it: <code>{}</code></span>",
                    esc(&fix)
                ));
            }
            out.push_str("</li>");
        }
        out.push_str("</ul>");
    }
    out.push_str("</div>");
    scope_card(out, card);
    deep_card(out, card);
    runs(out, card);
    out.push_str("</div></section>\n");
}

fn scope_card(out: &mut String, card: &Scorecard) {
    out.push_str(&format!(
        "<div class=\"card\"><h3>Scope</h3><p><code>{}</code>",
        esc(&card.scope.mode)
    ));
    if let Some(base) = &card.scope.base {
        out.push_str(&format!(" against <code>{}</code>", esc(base)));
    }
    out.push_str("</p>");
    if let Some(intent) = card
        .intent
        .as_deref()
        .map(str::trim)
        .filter(|i| !i.is_empty())
    {
        out.push_str(&format!("<p>Intent: {}</p>", esc(intent)));
    }
    let paths = &card.scope.paths;
    if !paths.is_empty() {
        out.push_str(&format!(
            "<details><summary>{}</summary><ul class=\"pathlist\">",
            plural(paths.len(), "path", "paths")
        ));
        for path in paths {
            out.push_str(&format!(
                "<li>{}</li>",
                path_html(&rel_path(path, &card.repo), None)
            ));
        }
        out.push_str("</ul></details>");
    }
    out.push_str("</div>");
}

fn deep_card(out: &mut String, card: &Scorecard) {
    out.push_str("<div class=\"card\"><h3>Spec and mutation</h3>");
    match &card.spec.path {
        Some(path) => {
            out.push_str(&format!(
                "<p>Spec {} · {}</p>",
                path_html(path, None),
                plural(card.spec.gaps.len(), "gap", "gaps")
            ));
            for gap in &card.spec.gaps {
                out.push_str(&format!("<pre>{}</pre>", esc(&gap.to_string())));
            }
        }
        None => out.push_str("<p class=\"note\">Spec: not requested.</p>"),
    }
    let m = &card.mutation;
    if m.status == "skipped" || m.status == "off" {
        out.push_str("<p class=\"note\">Mutation: not run.</p>");
    } else {
        out.push_str(&format!(
            "<p>Mutation {}{}: {} killed, {} survived, {} timed out.</p>",
            esc(&m.status),
            m.score
                .map(|s| format!(", score {s:.2}"))
                .unwrap_or_default(),
            m.killed,
            m.survived,
            m.timeout
        ));
    }
    out.push_str("</div>");
}

fn runs(out: &mut String, card: &Scorecard) {
    out.push_str("<div class=\"card wide\"><h3>Commands</h3>");
    if card.runs.is_empty() {
        out.push_str("<p class=\"note\">No external commands ran.</p></div>");
        return;
    }
    out.push_str("<table class=\"stack\"><colgroup><col class=\"c-eng\"><col><col class=\"c-exit\"><col class=\"c-ms\"></colgroup><thead><tr><th scope=\"col\">engine</th><th scope=\"col\">command</th><th scope=\"col\">exit</th><th scope=\"col\">ms</th></tr></thead><tbody>");
    for run in &card.runs {
        let exit = match run.exit_code {
            Some(0) => "<span class=\"pill p-info\">0</span>".to_string(),
            Some(code) => format!("<span class=\"pill p-error\">{code}</span>"),
            None => "<span class=\"nm\">none</span>".to_string(),
        };
        out.push_str(&format!(
            "<tr><td data-label=\"engine\"><code>{}</code></td><td data-label=\"command\"><pre>{}</pre></td><td data-label=\"exit\">{exit}</td><td data-label=\"ms\">{}</td></tr>",
            esc(&run.engine),
            esc(&run.command),
            run.duration_ms
        ));
    }
    out.push_str("</tbody></table></div>");
}

fn esc(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(c),
        }
    }
    out
}

