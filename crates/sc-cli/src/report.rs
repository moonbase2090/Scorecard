    #[test]
    fn long_strings_wrap_or_elide_so_nothing_scrolls_sideways() {
        let hash = "c9360261a1ec36ad194552ee4968ce6b5da156849d62a9a24254e6aa0c66aae1";
        let file = format!("infra/cdk.out/asset.{hash}/vectorvault/memory_client.py");
        let mut c = card();
        let mut f = finding(
            "crap.over_threshold",
            "crap",
            "warning",
            &file,
            "MemoryClient.pin_working_set",
        );
        f.id = format!("crap:{file}:MemoryClient.pin_working_set");
        f.message = format!("token {hash}{hash} in {file}");
        c.findings.push(f);
        c.git.head = Some(hash.into());
        let html = to_html(&c);
        // Every long path is an elided .path box with the full value on hover.
        assert!(html.contains(&format!("title=\"{file}\"")));
        assert!(html.contains(&format!(
            "<span class=\"ph\">infra/cdk.out/asset.{hash}/vectorvault/</span>"
        )));
        // Everything else wraps anywhere, and every nowrap rule clips.
        assert!(CSS.contains("html,body{margin:0;background:var(--bg);color:var(--ink);font:15px/1.5 var(--sans);\noverflow-wrap:anywhere}"));
        assert!(CSS.contains("pre{white-space:pre-wrap;overflow-wrap:anywhere;margin:0}"));
        for rule in CSS.split('}').filter(|r| r.contains("white-space:nowrap")) {
            let bounded = rule.contains("overflow:hidden")
                || rule.starts_with("\n.pill{")
                || rule.contains(".sr-only");
            assert!(bounded, "nowrap without clipping: {rule}");
        }
        // No layout width cap: the page is fluid.
        assert!(!CSS.contains("max-width:880px"));
        // Tables stack into label/value rows on phones.
        assert!(CSS.contains("table.stack td::before{content:attr(data-label)"));
    }

