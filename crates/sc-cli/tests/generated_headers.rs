use std::path::Path;
use std::process::Command;

fn analyze(root: &Path) -> serde_json::Value {
    let output = Command::new(env!("CARGO_BIN_EXE_sc"))
        .current_dir(root)
        .env("SCORECARD_NO_AGENT_SKILLS", "1")
        .args([
            "analyze",
            ".",
            "--format",
            "json",
            "--fail-on",
            "secrets",
            "--quiet",
        ])
        .output()
        .unwrap();
    let card: serde_json::Value = serde_json::from_slice(&output.stdout).unwrap();
    assert_eq!(output.status.code(), Some(1), "{card}");
    let finding = card["findings"]
        .as_array()
        .unwrap()
        .iter()
        .find(|finding| finding["rule"] == "secrets.github_token")
        .expect("fixture token must be found");
    assert_eq!(finding["file"], "src/lib.rs");
    let gate = card["gates"]
        .as_array()
        .unwrap()
        .iter()
        .find(|gate| gate["id"] == "secrets")
        .unwrap();
    assert_eq!(gate["pass"], false);
    card
}

#[test]
fn issue_237_repros_and_real_headers_cannot_hide_secrets() {
    let root = std::env::temp_dir().join(format!("sc-generated-headers-{}", std::process::id()));
    let _ = std::fs::remove_dir_all(&root);
    std::fs::create_dir_all(root.join("src")).unwrap();
    std::fs::write(root.join("analyzer.toml"), "pack = \"web\"\n").unwrap();
    let fixture = std::fs::read_to_string(
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../testdata/secret_token/src/lib.rs"),
    )
    .unwrap();
    for in_git in [false, true] {
        if in_git {
            assert!(Command::new("git")
                .args(["init", "-q"])
                .current_dir(&root)
                .status()
                .unwrap()
                .success());
        }
        for prefix in [
            "// notes about @generated markers\n".to_string(),
            "// This code generated the report.\n// Please DO NOT EDIT the deployment notes.\n"
                .to_string(),
            format!("{}// @generated\n", "// padding\n".repeat(1700)),
        ] {
            std::fs::write(root.join("src/lib.rs"), format!("{prefix}{fixture}")).unwrap();
            let card = analyze(&root);
            assert!(card["generated_files_warning"].is_null(), "{card}");
        }
        for prefix in [
            "// @generated\n",
            "// Code generated by tool; DO NOT EDIT.\n",
        ] {
            std::fs::write(root.join("src/lib.rs"), format!("{prefix}{fixture}")).unwrap();
            let card = analyze(&root);
            assert_eq!(
                card["generated_files_warning"]["skipped_files"],
                serde_json::json!(["src/lib.rs"])
            );
            assert_eq!(
                card["generated_files_warning"]["files"],
                serde_json::json!([])
            );
            assert!(card["generated_files_warning"]["suggested_action"]
                .as_str()
                .unwrap()
                .contains("scope.include_generated"));
        }
        std::fs::write(
            root.join("analyzer.toml"),
            "pack = \"web\"\n[scope]\ninclude_generated = [\"src/lib.rs\"]\n",
        )
        .unwrap();
        let card = analyze(&root);
        assert_eq!(
            card["generated_files_warning"]["files"],
            serde_json::json!(["src/lib.rs"])
        );
        assert!(card["generated_files_warning"]["skipped_files"].is_null());
        std::fs::write(root.join("analyzer.toml"), "pack = \"web\"\n").unwrap();
    }
    std::fs::remove_dir_all(root).unwrap();
}
